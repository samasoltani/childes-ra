    "میزان","مقدار","تعداد","درصد","عدد","نرخ","قیمت","هزینه","سود","خسارت","لطمه",
    "آسیب","ضربه","زخم","درد","قرارداد","حکومت","دولت","سیاست","انقلاب","جنگ","جلسه",
