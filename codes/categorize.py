    "حق","زندگی","مشکل","ارزش","قصد","قدرت","نظر","نیاز","اهمیت","احساس","توجه",
    "امکان","وظیفه","عشق","اعتقاد","معنا","تأثیر","حقیقت","نتیجه","فکر","علاقه","دین",
    "دلیل","ایمان","رابطه","رفتار","واقعیت","انتظار","گناه","مسئولیت","وجود","خشم",
    "لذت","تفاوت","تمایل","محبت","تجربه","عادت","امید","مفهوم","زیبایی","حس","حالت",
